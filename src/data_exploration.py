
def show_head (df):
    return df.head()

def show_tail (df):
    return df.tail()

def show_shape(df):
    return df.shape

def show_info(df):
    return df.info()

def show_isna(df):
    return df.isna()

def show_duplicated(df):
    return df.duplicated()

def show_nunique(df):
    return df.nunique()